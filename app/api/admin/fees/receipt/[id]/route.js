import { NextResponse } from "next/server";
import { getCurrentUser } from "@/lib/auth";
import { hasPermission } from "@/lib/permissions";
import { db } from "@/lib/db";

export async function GET(_req, { params }) {
  const user = await getCurrentUser();
  if (!user || !hasPermission(user, "fees.view")) {
    return new NextResponse("Forbidden", { status: 403 });
  }

  const { id } = await params;
  const ledger = await db.feeLedger.findUnique({
    where: { id },
    include: {
      student: { select: { name: true, registrationNo: true, phone: true, email: true } },
      batchEnrollment: { include: { batch: { select: { code: true, name: true } } } },
      payments: { orderBy: { createdAt: "asc" } },
    },
  });

  if (!ledger) return new NextResponse("Fee ledger not found", { status: 404 });

  const esc = (v) =>
    String(v ?? "").replace(/[&<>"']/g, (c) => ({
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    }[c]));

  const rows = ledger.payments.map((p) =>
    "<tr><td>" +
    esc(p.paidAt ? new Date(p.paidAt).toLocaleString("en-IN") : "") +
    "</td><td>" + esc(p.method) +
    "</td><td>" + esc(p.reference || "—") +
    "</td><td class='amount'>₹" +
    Number(p.amount).toLocaleString("en-IN", { maximumFractionDigits: 2 }) +
    "</td></tr>"
  ).join("");

  const html = `<!doctype html>
<html><head><meta charset="utf-8"><title>RCLD Fee Receipt</title>
<style>
body{font-family:Arial,sans-serif;background:#f4f7fb;color:#0f172a;margin:0;padding:30px}
.receipt{max-width:760px;margin:auto;background:white;padding:36px;border:1px solid #e2e8f0;box-shadow:0 20px 60px rgba(15,23,42,.08)}
.top{display:flex;justify-content:space-between;border-bottom:2px solid #0f172a;padding-bottom:18px}
.brand{font-size:22px;font-weight:800}.muted{color:#64748b;font-size:12px}
.grid{display:grid;grid-template-columns:1fr 1fr;gap:12px;margin:24px 0}
.box{border:1px solid #e2e8f0;border-radius:10px;padding:12px}.box b{display:block;margin-top:5px}
.title{font-size:18px;font-weight:800;margin:26px 0 12px}
table{width:100%;border-collapse:collapse}th,td{padding:10px;border-bottom:1px solid #e2e8f0;text-align:left;font-size:12px}
th{background:#f8fafc}.amount{text-align:right;font-weight:800}
.total{margin-top:18px;margin-left:auto;max-width:300px}.line{display:flex;justify-content:space-between;padding:6px 0}
.grand{border-top:2px solid #0f172a;font-weight:800;font-size:16px;margin-top:6px;padding-top:10px}
.footer{margin-top:30px;text-align:center;color:#64748b;font-size:11px}
@media print{body{background:white;padding:0}.receipt{box-shadow:none;border:0;max-width:none}}
</style></head>
<body><div class="receipt">
<div class="top"><div><div class="brand">RCLD Islampur</div><div class="muted">Fee Collection Receipt</div></div>
<div class="muted">Generated ${esc(new Date().toLocaleString("en-IN"))}</div></div>
<div class="grid">
<div class="box"><span class="muted">Student</span><b>${esc(ledger.student.name)}</b><span class="muted">${esc(ledger.student.registrationNo || "—")}</span></div>
<div class="box"><span class="muted">Batch</span><b>${esc(ledger.batchEnrollment.batch.name)}</b><span class="muted">${esc(ledger.batchEnrollment.batch.code)}</span></div>
</div>
<div class="title">Payment history</div>
<table><thead><tr><th>Date</th><th>Method</th><th>Reference</th><th class="amount">Amount</th></tr></thead>
<tbody>${rows || "<tr><td colspan='4'>No payments recorded</td></tr>"}</tbody></table>
<div class="total">
<div class="line"><span>Course fee</span><b>₹${Number(ledger.courseFee).toLocaleString("en-IN",{maximumFractionDigits:2})}</b></div>
<div class="line"><span>Discount</span><b>₹${Number(ledger.discountAmount).toLocaleString("en-IN",{maximumFractionDigits:2})}</b></div>
<div class="line"><span>Paid</span><b>₹${Number(ledger.paidAmount).toLocaleString("en-IN",{maximumFractionDigits:2})}</b></div>
<div class="line grand"><span>Balance</span><span>₹${Number(ledger.balanceAmount).toLocaleString("en-IN",{maximumFractionDigits:2})}</span></div>
</div>
<div class="footer">This receipt is generated by the RCLD Islampur ERP. Keep it for your records.</div>
</div><script>window.onload=()=>window.print()</script></body></html>`;

  return new NextResponse(html, {
    status: 200,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      "Cache-Control": "no-store",
    },
  });
}
